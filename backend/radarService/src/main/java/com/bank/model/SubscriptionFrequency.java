package com.bank.model;

public enum SubscriptionFrequency {
    /**
     * Еженедельная подписка (каждые ~7 дней)
     */
    WEEKLY,
    
    /**
     * Ежемесячная подписка (каждые ~30 дней)
     */
    MONTHLY,
    
    /**
     * Квартальная подписка (каждые ~90 дней)
     */
    QUARTERLY,
    
    /**
     * Полугодовая подписка (каждые ~180 дней)
     */
    SEMI_ANNUALLY,
    
    /**
     * Годовая подписка (каждые ~365 дней)
     */
    ANNUALLY,
    
    /**
     * Нестандартная периодичность
     */
    CUSTOM
}

